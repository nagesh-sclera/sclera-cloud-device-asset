    /**
     * {@inheritDoc} Derives the transition type (create vs. update), persists via the native upsert, writes history, and emits an audit event; each side-step guards its own errors.
     *
     * <p>Intentionally <strong>not</strong> {@code @Transactional}: this method relies on the
     * primary ticket write committing in its own (repository-level) transaction <em>before</em> the
     * best-effort side-effects run. Wrapping it in a single transaction would (a) let a swallowed
     * history-write failure mark the shared transaction rollback-only → {@code UnexpectedRollbackException}
     * at commit, and (b) break the foreign key for new tickets, whose history row would reference a
     * ticket that has not been committed yet. The per-step commit design is deliberate.
     */
    @Override
    public void upsertTicket(String username, String vdmsId, TicketDTO ticketDTO) {
        try {
            TicketType ticket_type = TicketType.NO_CHANGES;
            BigInteger timestamp = BigInteger.valueOf(System.currentTimeMillis());

            // Case 1: Creating a new ticket
            if (ticketDTO.getId() == null) {
                String newId = Generators.timeBasedGenerator().generate().toString();
                ticketDTO.setId(newId);
                ticketDTO.setCreated_at(timestamp);
                ticketDTO.setCreated_by(username);
                ticketDTO.setNumber(getNextTicketNumberByCategory(ticketDTO.getCategory(), vdmsId));
                ticketDTO.setName(getTicketNameByCategory(ticketDTO));
                ticketDTO.setDescription(ticketDTO.getUser_message());
                ticket_type = TicketType.GENERATED_BY_CUSTOMER; // Ticket Generated by Customer and is new ticket
                ticketDTO.setType(String.valueOf(ticket_type.getValue()));
                if (ticketDTO.getStatus() == null) {
                    ticketDTO.setStatus("new");
                }

            }

            // Case 2: Updating an existing ticket
            if (ticket_type == TicketType.NO_CHANGES) {
                try {
                    TicketDTO ticketDataOld = ticketRepository.getNativeTicketById(ticketDTO.getId());
                    String oldTicketStatus = ticketDataOld.getStatus();
                    String newTicketStatus = ticketDTO.getStatus();
                    String oldTicketUserMessage = ticketDataOld.getUser_message();
                    String newTicketUserMessage = ticketDTO.getUser_message();
                    String oldAssigneeUserEmail = ticketDataOld.getAssignee_user_email();
                    String newAssigneeUserEmail = ticketDTO.getAssignee_user_email();


                    ticket_type = determineTicketType(oldTicketStatus, newTicketStatus, oldTicketUserMessage, newTicketUserMessage, oldAssigneeUserEmail, newAssigneeUserEmail);


                    if (ticket_type == TicketType.CLOSED) { // Ticket Closed
                        ticketDTO.setClosed_at(timestamp);
                        ticketDTO.setClosed_by(username);
                    }

                    ticketDTO.setType(String.valueOf(ticket_type.getValue()));
                    ticketDTO.setUpdated_at(timestamp);
                    ticketDTO.setUpdated_by(username);
                    ticketDTO.setNumber(ticketDataOld.getNumber());
                    ticketDTO.setName(ticketDataOld.getName());
                    ticketDTO.setDescription(ticketDataOld.getDescription());
                    ticketDTO.setCreated_by(ticketDataOld.getCreated_by());


                } catch (Exception e) {
                    log.error("Error updating ticket type for ticket ID: {}: {}", ticketDTO.getId(), e.getMessage(), e);
                }

            }

            log.debug("Ticket Type: {} for Ticket ID: {}", ticket_type, ticketDTO.getId());
            ticketRepository.upsertTicketNative(
                    ticketDTO.getId(), ticketDTO.getNumber(), ticketDTO.getStatus(), ticketDTO.getUser_message(),
                    ticketDTO.getType(), ticketDTO.getDescription(), ticketDTO.getCategory(), ticketDTO.getRequest_type(),
                    ticketDTO.getCreated_by(), ticketDTO.getCreated_at(), ticketDTO.getUpdated_by(), ticketDTO.getUpdated_at(),
                    ticketDTO.getClosed_by(), ticketDTO.getClosed_at(), ticketDTO.getDevice_id(),
                    ticketDTO.getAssignee_user_email(), ticketDTO.getName()
            );
            log.info("Successfully added ticket ID: {} to database : {}", ticketDTO.getId(), ticketDTO);

            // ✅ Add user action log
            String action = ticket_type == TicketType.GENERATED_BY_CUSTOMER ? "ADD" : "UPDATE";

            try {
                String message = ticket_type == TicketType.GENERATED_BY_CUSTOMER ? "Ticket added successfully" : "Ticket updated successfully";

                userActionLogService.addUserAction(
                        username, vdmsId, "tickets", action, message, "success", "native_tickets", ticketDTO.getId()
                );
                log.info("User action logged for ticket ID: {}", ticketDTO.getId());
            } catch (Exception e) {
                userActionLogService.addUserAction(
                        username, vdmsId, "tickets", action, "Failed to " + action.toLowerCase() + " ticket", "failed", "native_tickets", ticketDTO.getId()
                );
                log.error("Error logging user action for ticket ID: {}: {}", ticketDTO.getId(), e.getMessage(), e);
            }


            // Insert ticket update into history
            try {
                if (ticket_type != TicketType.NO_CHANGES) {
                    String actionMessage = getTicketHistoryMessage(ticket_type, ticketDTO.getNumber(), username,
                            ticketDTO.getStatus(), ticketDTO.getAssignee_user_email());


                    //check if user_message is changed, if its changed then add user message to history or else  set user_message as null
                    String historyMessage;
                    if (ticket_type == TicketType.GENERATED_BY_CUSTOMER ||
                            ticket_type == TicketType.MESSAGE_UPDATED_BY_CUSTOMER ||
                            ticket_type == TicketType.STATUS_AND_MESSAGE_UPDATED_BY_CUSTOMER ||
                            ticket_type == TicketType.MESSAGE_UPDATED_AND_ASSIGNED ||
                            ticket_type == TicketType.STATUS_AND_MESSAGE_UPDATED_AND_ASSIGNED ||
                            ticket_type == TicketType.MESSAGE_UPDATED_AND_UNASSIGNED ||
                            ticket_type == TicketType.STATUS_AND_MESSAGE_UPDATED_AND_UNASSIGNED) {
                        historyMessage = ticketDTO.getUser_message();
                    } else {
                        historyMessage = null;
                    }

                    ticketHistoryService.addNativeTicketHistory(historyMessage, timestamp, ticketDTO.getStatus(), actionMessage, ticketDTO.getNumber(), username, ticketDTO.getId());
                    log.info("Successfully inserted ticket history for ticket ID: {}", ticketDTO.getId());
                }
            } catch (Exception e) {

                log.error("Error inserting ticket history for ticket ID: {}: {}", ticketDTO.getId(), e.getMessage(), e);
            }

            // Send ticket alert
            try {
                ticketDTO.setTimestamp(timestamp);
                this.sendNativeTicketAlertInfo(ticketDTO, ticket_type);
                log.info("Successfully sent ticket alert for ticket ID: {}", ticketDTO.getId());
            } catch (Exception e) {
                log.error("Error sending ticket alert for ticket ID: {}: {}", ticketDTO.getId(), e.getMessage(), e);
            }

            // Update ticket count and status (side effect — failure must not undo the DB write)
            try {
                deviceAssetClient.syncTicketStats(ticketDTO.getDevice_id());
                log.info("Successfully updated device ticket count and status for device ID: {}", ticketDTO.getDevice_id());
            } catch (Exception syncEx) {
                log.warn("Failed to sync ticket stats for device ID: {}: {}", ticketDTO.getDevice_id(), syncEx.getMessage());
            }
        } catch (RuntimeException e) {
            log.error("Error in upsertTicket for username: {}, ticketDTO: {}: {}", username, ticketDTO, e.getMessage(), e);
            throw e;
        }
    }

    /** {@inheritDoc} Computes the next sequential ticket number for the category from the latest existing number. */
    @Override
    @Transactional(readOnly = true)
    public String getNextTicketNumberByCategory(String category, String vdmsId) {
        String prefix = "";

        // Strip a leading "VDMS" prefix case-insensitively (VDMS000 / vdms000 → 000).
        String numericId = vdmsId.regionMatches(true, 0, "VDMS", 0, 4) ? vdmsId.substring(4) : vdmsId;

        if (category.equalsIgnoreCase("incident_request")) {
            prefix = "INC-" + numericId;
        } else if (category.equalsIgnoreCase("service_request")) {
            prefix = "SRN-" + numericId;
        }
        Integer maxNum = ticketRepository.findMaxTicketNumberByPrefix(prefix);
        int nextNumber = (maxNum == null ? 0 : maxNum) + 1;
        return prefix + String.format("%06d", nextNumber);
    }

