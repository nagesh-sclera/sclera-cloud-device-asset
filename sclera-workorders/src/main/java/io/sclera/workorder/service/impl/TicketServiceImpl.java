    private String getTicketHistoryMessage(TicketType ticketType, String ticketNumber, String username,
                                           String newStatus, String newAssigneeUserEmail) {
        String historyMessage;

        switch (ticketType) {
            case NO_CHANGES:
                historyMessage = "Ticket #" + ticketNumber + " remains unchanged by " + username;
                break;
            case GENERATED_BY_CUSTOMER:
                historyMessage = "Ticket #" + ticketNumber + " was created by " + username;
                break;
            case STATUS_UPDATED_BY_CUSTOMER:
                historyMessage = "Ticket #" + ticketNumber + " status changed to " + newStatus + " by " + username;
                break;
            case MESSAGE_UPDATED_BY_CUSTOMER:
                historyMessage = "Ticket #" + ticketNumber + " message updated by customer " + username;
                break;
            case STATUS_AND_MESSAGE_UPDATED_BY_CUSTOMER:
                historyMessage = "Ticket #" + ticketNumber + " status changed to " + newStatus + " and message updated by " + username;
                break;
            case STATUS_UPDATED_BY_VENDOR:
                historyMessage = "Ticket #" + ticketNumber + " status changed to " + newStatus + " by vendor " + username;
                break;
            case MESSAGE_UPDATED_BY_VENDOR:
                historyMessage = "Ticket #" + ticketNumber + " vendor message updated by " + username;
                break;
            case STATUS_AND_MESSAGE_UPDATED_BY_VENDOR:
                historyMessage = "Ticket #" + ticketNumber + " status changed to " + newStatus + " with vendor message updated by " + username;
                break;
            case REOPENED_BY_CUSTOMER:
                historyMessage = "Ticket #" + ticketNumber + " has been re-opened by " + username;
                break;
            case ASSIGNED:
                historyMessage = "Ticket #" + ticketNumber + " assigned to " + newAssigneeUserEmail + " by " + username;
                break;
            case STATUS_UPDATED_AND_ASSIGNED:
                historyMessage = "Ticket #" + ticketNumber + " status updated to " + newStatus + " and assigned to " + newAssigneeUserEmail + " by " + username;
                break;
            case MESSAGE_UPDATED_AND_ASSIGNED:
                historyMessage = "Ticket #" + ticketNumber + " message updated and assigned to " + newAssigneeUserEmail + " by " + username;
                break;
            case STATUS_AND_MESSAGE_UPDATED_AND_ASSIGNED:
                historyMessage = "Ticket #" + ticketNumber + " status changed to " + newStatus + ", message updated, and assigned to " + newAssigneeUserEmail + " by " + username;
                break;
            case UNASSIGNED:
                historyMessage = "Ticket #" + ticketNumber + " unassigned by " + username;
                break;
            case STATUS_UPDATED_AND_UNASSIGNED:
                historyMessage = "Ticket #" + ticketNumber + " status changed to " + newStatus + " and unassigned by " + username;
                break;
            case MESSAGE_UPDATED_AND_UNASSIGNED:
                historyMessage = "Ticket #" + ticketNumber + " message updated and unassigned by " + username;
                break;
            case STATUS_AND_MESSAGE_UPDATED_AND_UNASSIGNED:
                historyMessage = "Ticket #" + ticketNumber + " status changed to " + newStatus + ", message updated, and unassigned by " + username;
                break;
            case CLOSED:
                historyMessage = "Ticket #" + ticketNumber + " was closed by " + username;
                break;
            default:
                historyMessage = "Ticket #" + ticketNumber + " performed an unknown action by " + username;
                break;
        }
        return historyMessage;
    }

