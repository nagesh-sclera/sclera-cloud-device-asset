    /**
     * Determines the ticket type based on changes in status, user message and assignment
     */
    private TicketType determineTicketType(String oldStatus, String newStatus, String oldUserMessage,
                                           String newUserMessage, String oldAssigneeUserEmail,
                                           String newAssigneeUserEmail) {
        TicketType ticketType = TicketType.NO_CHANGES;

        // Determine ticketType using if-else
        if (newStatus != null && newStatus.equalsIgnoreCase("closed")) {
            ticketType = TicketType.CLOSED; // Ticket Closed (highest priority)

        } else if (oldStatus != null && newStatus != null && oldStatus.equals("closed") && !newStatus.equals("closed")) {
            ticketType = TicketType.REOPENED_BY_CUSTOMER; // Re-Opened by Customer

        } else if (oldStatus != null && newStatus != null && !oldStatus.equals(newStatus) &&
                oldUserMessage != null && newUserMessage != null && !oldUserMessage.equals(newUserMessage) &&
                ((oldAssigneeUserEmail == null || oldAssigneeUserEmail.trim().isEmpty()) && newAssigneeUserEmail != null && !newAssigneeUserEmail.trim().isEmpty() ||
                        !(oldAssigneeUserEmail == null || oldAssigneeUserEmail.trim().isEmpty()) && newAssigneeUserEmail != null && !newAssigneeUserEmail.trim().isEmpty() && !oldAssigneeUserEmail.equals(newAssigneeUserEmail))) {
            ticketType = TicketType.STATUS_AND_MESSAGE_UPDATED_AND_ASSIGNED; // Status Updated + User Message Updated + Assignment Changed

        } else if (oldStatus != null && newStatus != null && !oldStatus.equals(newStatus) &&
                oldUserMessage != null && newUserMessage != null && !oldUserMessage.equals(newUserMessage) &&
                !(oldAssigneeUserEmail == null || oldAssigneeUserEmail.trim().isEmpty()) && (newAssigneeUserEmail == null || newAssigneeUserEmail.trim().isEmpty())) {
            ticketType = TicketType.STATUS_AND_MESSAGE_UPDATED_AND_UNASSIGNED; // Status Updated + User Message Updated + Unassigned

        } else if (oldStatus != null && newStatus != null && !oldStatus.equals(newStatus) &&
                ((oldAssigneeUserEmail == null || oldAssigneeUserEmail.trim().isEmpty()) && newAssigneeUserEmail != null && !newAssigneeUserEmail.trim().isEmpty() ||
                        !(oldAssigneeUserEmail == null || oldAssigneeUserEmail.trim().isEmpty()) && newAssigneeUserEmail != null && !newAssigneeUserEmail.trim().isEmpty() && !oldAssigneeUserEmail.equals(newAssigneeUserEmail))) {
            ticketType = TicketType.STATUS_UPDATED_AND_ASSIGNED; // Status Updated + Assignment Changed

        } else if (oldStatus != null && newStatus != null && !oldStatus.equals(newStatus) &&
                !(oldAssigneeUserEmail == null || oldAssigneeUserEmail.trim().isEmpty()) && (newAssigneeUserEmail == null || newAssigneeUserEmail.trim().isEmpty())) {
            ticketType = TicketType.STATUS_UPDATED_AND_UNASSIGNED; // Status Updated + Unassigned

        } else if (oldUserMessage != null && newUserMessage != null && !oldUserMessage.equals(newUserMessage) &&
                ((oldAssigneeUserEmail == null || oldAssigneeUserEmail.trim().isEmpty()) && newAssigneeUserEmail != null && !newAssigneeUserEmail.trim().isEmpty() ||
                        !(oldAssigneeUserEmail == null || oldAssigneeUserEmail.trim().isEmpty()) && newAssigneeUserEmail != null && !newAssigneeUserEmail.trim().isEmpty() && !oldAssigneeUserEmail.equals(newAssigneeUserEmail))) {
            ticketType = TicketType.MESSAGE_UPDATED_AND_ASSIGNED; // User Message Updated + Assignment Changed

        } else if (oldUserMessage != null && newUserMessage != null && !oldUserMessage.equals(newUserMessage) &&
                !(oldAssigneeUserEmail == null || oldAssigneeUserEmail.trim().isEmpty()) && (newAssigneeUserEmail == null || newAssigneeUserEmail.trim().isEmpty())) {
            ticketType = TicketType.MESSAGE_UPDATED_AND_UNASSIGNED; // User Message Updated + Unassigned

        } else if (oldStatus != null && newStatus != null && !oldStatus.equals(newStatus) &&
                oldUserMessage != null && newUserMessage != null && !oldUserMessage.equals(newUserMessage)) {
            ticketType = TicketType.STATUS_AND_MESSAGE_UPDATED_BY_CUSTOMER; // Status Updated + User Message Updated

        } else if (oldStatus != null && newStatus != null && !oldStatus.equals(newStatus)) {
            ticketType = TicketType.STATUS_UPDATED_BY_CUSTOMER; // Status Updated by Customer

        } else if (oldUserMessage != null && newUserMessage != null && !oldUserMessage.equals(newUserMessage)) {
            ticketType = TicketType.MESSAGE_UPDATED_BY_CUSTOMER; // User Message Updated by Customer

        } else if ((oldAssigneeUserEmail == null || oldAssigneeUserEmail.trim().isEmpty()) && newAssigneeUserEmail != null && !newAssigneeUserEmail.trim().isEmpty() ||
                !(oldAssigneeUserEmail == null || oldAssigneeUserEmail.trim().isEmpty()) && newAssigneeUserEmail != null && !newAssigneeUserEmail.trim().isEmpty() && !oldAssigneeUserEmail.equals(newAssigneeUserEmail)) {
            ticketType = TicketType.ASSIGNED; // Assignment Changed

        } else if (!(oldAssigneeUserEmail == null || oldAssigneeUserEmail.trim().isEmpty()) && (newAssigneeUserEmail == null || newAssigneeUserEmail.trim().isEmpty())) {
            ticketType = TicketType.UNASSIGNED; // Unassigned

        } else {
            ticketType = TicketType.NO_CHANGES; // No changes
        }

        return ticketType;
    }


    /** {@inheritDoc} Sanitizes the search key and runs the filtered, paged query (LIMIT/OFFSET via Pageable). */
    @Override
    @Transactional(readOnly = true)
    public Set<TicketDTO> getAllTickets(String username, String searchkey, TicketFilterDTO ticketFilterDTO, Integer pagesize, Integer pageno) {
        Set<String> statusSet = ticketFilterDTO.getStatus();
        String status = (statusSet == null || statusSet.isEmpty() || statusSet.contains("all")) ? "all"
                : statusSet.iterator().next();
        return new LinkedHashSet<>(ticketRepository.getAllNativeTickets(searchkey, ticketFilterDTO.getCategory(), status,
                ticketFilterDTO.getAssignee_user_email(), ticketFilterDTO.getDevice_id(), username,
                PageRequest.of(pageno - 1, pagesize)));
    }


