    /** {@inheritDoc} Soft-deletes the ticket and records the audit action; rethrows on failure (after a failed-audit entry). */
    @Override
    @Transactional
    public void deleteTicketById(String username, String vdmsId, String ticket_id) {
        try {
            TicketDTO ticketDTO = ticketRepository.getNativeTicketById(ticket_id);

            // Delete ticket
            ticketRepository.deleteTicketById(ticket_id);

            // Update device ticket status/count
            deviceAssetClient.syncTicketStats(ticketDTO.getDevice_id());
            // Log deletion in user action
            userActionLogService.addUserAction(username, vdmsId, "tickets", "DELETE", "Ticket deleted successfully", "success", "native_tickets", ticket_id);
            log.info("Deleted ticket ID: {} by user: {}", ticket_id, username);
        } catch (RuntimeException e) {
            userActionLogService.addUserAction(username, vdmsId, "tickets", "DELETE", "Failed to delete ticket", "failed", "native_tickets", ticket_id);
            log.error("Unable to delete ticket ID: {} by user: {}", ticket_id, username);
            throw e;
        }
    }

